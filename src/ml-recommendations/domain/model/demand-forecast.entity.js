/**
 * @typedef {Object} ForecastDataPoint
 * @property {string} date yyyy-mm-dd
 * @property {string} dayLabel
 * @property {string} dishName dish with the most projected units that day
 * @property {number} projectedUnits total units of every dish that day
 * @property {number} [tempMaxC]
 * @property {number} [precipitationMm]
 * @property {{dishName: string, projectedUnits: number}[]} [dishes] detail per dish
 */

/**
 * @typedef {Object} DemandForecastProps
 * @property {number} [id]
 * @property {string} [generatedAt]
 * @property {number} [confidenceScore] between 0 and 1
 * @property {string} [weatherCondition] SUNNY | CLOUDY | DRIZZLE | RAIN
 * @property {string} [weatherSource] open-meteo | climatology
 * @property {string} [method] MACHINE_LEARNING | BASELINE
 * @property {string} [modelVersion]
 * @property {ForecastDataPoint[]} [dataPoints]
 */

/**
 * Aggregate root of the ML & Recommendations Bounded Context: projected units
 * per day for the next seven days.
 *
 * @remarks
 * Generated by the StockIA Platform API: `method` tells whether the Machine
 * Learning model or the same-weekday baseline (little sales history) was used.
 */
export class DemandForecast {
  /**
   * @param {DemandForecastProps} [props]
   */
  constructor({
    id = 0, generatedAt = '', confidenceScore = 0, weatherCondition = '', weatherSource = '', method = '', modelVersion = '', dataPoints = [],
  } = {}) {
    this.id = id;
    this.generatedAt = generatedAt;
    this.confidenceScore = Number(confidenceScore);
    this.weatherCondition = weatherCondition;
    this.weatherSource = weatherSource;
    this.method = method;
    this.modelVersion = modelVersion;
    this.dataPoints = dataPoints.map((point) => ({ ...point, projectedUnits: Number(point.projectedUnits) }));
  }

  /** @returns {number} highest projected units of the period (at least 1) */
  get maxProjectedUnits() {
    return Math.max(1, ...this.dataPoints.map((point) => point.projectedUnits));
  }

  /** @returns {number} total projected units of the period */
  get totalProjectedUnits() {
    return this.dataPoints.reduce((sum, point) => sum + point.projectedUnits, 0);
  }
}
